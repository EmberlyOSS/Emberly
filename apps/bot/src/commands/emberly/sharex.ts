import { AttachmentBuilder, ChatInputCommandInteraction, EmbedBuilder, MessageFlags, SlashCommandBuilder } from 'discord.js'
import db from '../../lib/db'
import { emberlyApi } from '../../lib/emberlyApi'
import { ACCENT, notLinkedReply, handleApiError } from './_helpers'

export const data = new SlashCommandBuilder()
  .setName('sharex')
  .setDescription('Get your Emberly ShareX upload config (sent privately)')
  .setDMPermission(true)

export async function execute(interaction: ChatInputCommandInteraction) {
  await interaction.deferReply({ flags: MessageFlags.Ephemeral })
  try {
    const linked = await db.prisma.linkedEmberlyAccount.findUnique({ where: { discordId: interaction.user.id } })
    if (!linked) { await interaction.editReply(notLinkedReply()); return }

    // Generated by the site so it uses the user's preferred upload domain
    const config = await emberlyApi.getShareXConfig(linked.uploadToken)

    const attachment = new AttachmentBuilder(Buffer.from(JSON.stringify(config, null, 2), 'utf-8'), {
      name: 'emberly.sxcu',
      description: 'Emberly ShareX upload config',
    })

    const embed = new EmbedBuilder()
      .setColor(ACCENT)
      .setTitle('📋 Your ShareX Config')
      .setDescription(
        'Your `.sxcu` config file is attached. Open it, or in ShareX go to **Destinations → Custom uploader settings → Import**.\n\n' +
          '⚠️ **Keep this file private.** It contains your upload token.'
      )

    await interaction.editReply({ embeds: [embed], files: [attachment] })
  } catch (err) {
    await interaction.editReply(handleApiError(err, interaction))
  }
}
